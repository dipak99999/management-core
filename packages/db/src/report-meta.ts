// Doctype meta registry for the Report Builder.
//
// Each entry declares:
//   delegate — Prisma delegate name (camelCase model name)
//   columns  — reportable columns; keys are dotted paths ("customer.customerName")
//              matching what the frontend picker offers + the runner projects
//   filterableFields — columns that can appear in WHERE (subset of columns)
//   sortableFields   — columns that can appear in ORDER BY (subset)
//   defaultColumns   — pre-selected when a user opens the builder for the first time
//
// Adding a doctype: extend the object below, no other code changes needed.

export type ColumnType = "string" | "number" | "date" | "boolean" | "enum";

export interface ColumnMeta {
  key: string;              // dotted path, e.g. "customer.customerName"
  label: string;            // human-facing header
  type: ColumnType;
  choices?: string[];       // populated only when type = "enum"
}

export interface DoctypeMeta {
  doctype: string;          // "SalesInvoice"
  delegate: string;         // "salesInvoice"
  label: string;            // "Sales Invoices"
  columns: ColumnMeta[];
  filterableFields: string[];
  sortableFields: string[];
  defaultColumns: string[];
}

