import * as React from "react";
import { Image, Text, View } from "@react-pdf/renderer";

// Shared letterhead + format helpers so all 13 doctype templates can drop-in
// support Phase H tenant branding + Phase H format overrides + watermark +
// page-numbers footer + optional cover page.

export interface PrintLetterhead {
  logoBase64?: string | null;
  addressText?: string | null;
  footerText?: string | null;
}

export interface PrintFormatOverrides {
  headerText?: string | null;
  footerText?: string | null;
  thankYouNote?: string | null;
  termsText?: string | null;
  showItemDescription?: boolean;
  showTaxBreakdown?: boolean;
  showRemarks?: boolean;
  paperSize?: string;
  orientation?: string;
  watermark?: string | null; // "DRAFT" / "PAID" — overlays diagonally
}

export function LetterheadHeader({
  tenantName,
  docLabel,
  letterhead,
}: {
  tenantName: string;
  docLabel: string;
  letterhead?: PrintLetterhead | null;
}) {
  return (
    <View style={{ flexDirection: "row", alignItems: "flex-start", gap: 12 }}>
      {letterhead?.logoBase64 && (
        <Image
          src={letterhead.logoBase64}
          style={{ width: 64, height: 64, marginRight: 8 }}
        />
      )}
      <View>
        <Text style={{ fontSize: 16, fontFamily: "Helvetica-Bold" }}>{tenantName}</Text>
        <Text style={{ color: "#6b7280" }}>{docLabel}</Text>
        {letterhead?.addressText && (
          <Text style={{ color: "#6b7280", fontSize: 9, marginTop: 2 }}>
            {letterhead.addressText}
          </Text>
        )}
      </View>
    </View>
  );
}

// Rendered inside <Page>. Shows optional format headerText.
export function FormatHeaderBanner({
  format,
}: {
  format?: PrintFormatOverrides | null;
}) {
  if (!format?.headerText) return null;
  return (
    <View style={{ marginBottom: 12 }}>
      <Text style={{ color: "#374151" }}>{format.headerText}</Text>
    </View>
  );
}

export function FormatFooterBlocks({
  format,
}: {
  format?: PrintFormatOverrides | null;
}) {
  const bits: React.ReactNode[] = [];
  if (format?.thankYouNote) {
    bits.push(
      <View key="thanks" style={{ marginTop: 16 }}>
        <Text style={{ color: "#374151" }}>{format.thankYouNote}</Text>
      </View>,
    );
  }
  if (format?.termsText) {
    bits.push(
      <View key="terms" style={{ marginTop: 12 }}>
        <Text style={{ color: "#6b7280", fontSize: 9, marginBottom: 2 }}>
          Terms &amp; Conditions
        </Text>
        <Text style={{ color: "#6b7280", fontSize: 9 }}>{format.termsText}</Text>
      </View>,
    );
  }
  return <>{bits}</>;
}

// Diagonal watermark. Absolutely positioned; renders on every page it's mounted.
export function Watermark({ text }: { text?: string | null }) {
  if (!text) return null;
  return (
    <View
      style={{
        position: "absolute",
        top: "40%",
        left: 0,
        right: 0,
        alignItems: "center",
        opacity: 0.1,
      }}
      fixed
    >
      <Text
        style={{
          fontSize: 90,
          fontFamily: "Helvetica-Bold",
          color: "#9ca3af",
          transform: "rotate(-30deg)",
        }}
      >
        {text}
      </Text>
    </View>
  );
}

// Page-number footer with fixed prop so it appears on every page. Combined
// with the tenant/letterhead footer line.
export function PageFooter({
  format,
  letterhead,
}: {
  format?: PrintFormatOverrides | null;
  letterhead?: PrintLetterhead | null;
}) {
  const footerLine =
    format?.footerText ?? letterhead?.footerText ?? "Generated by lumaara";
  return (
    <View
      fixed
      style={{
        position: "absolute",
        bottom: 24,
        left: 32,
        right: 32,
        flexDirection: "row",
        justifyContent: "space-between",
        fontSize: 8,
        color: "#9ca3af",
      }}
    >
      <Text>
        {footerLine} · {new Date().toISOString().slice(0, 10)}
      </Text>
      <Text
        render={({ pageNumber, totalPages }) =>
          `Page ${pageNumber} of ${totalPages}`
        }
      />
    </View>
  );
}

// Optional cover page. Mount as the first <Page> in a Document.
export function CoverPage({
  tenantName,
  docTitle,
  docNumber,
  letterhead,
  meta,
}: {
  tenantName: string;
  docTitle: string;
  docNumber: string;
  letterhead?: PrintLetterhead | null;
  meta?: { label: string; value: string }[];
}) {
  return (
    <View
      style={{
        flex: 1,
        justifyContent: "center",
        alignItems: "center",
        padding: 40,
      }}
    >
      {letterhead?.logoBase64 && (
        <Image
          src={letterhead.logoBase64}
          style={{ width: 120, height: 120, marginBottom: 24 }}
        />
      )}
      <Text style={{ fontSize: 28, fontFamily: "Helvetica-Bold" }}>{tenantName}</Text>
      <Text style={{ fontSize: 20, color: "#6b7280", marginTop: 24 }}>{docTitle}</Text>
      <Text
        style={{ fontSize: 24, fontFamily: "Helvetica-Bold", marginTop: 8 }}
      >
        {docNumber}
      </Text>
      {meta && (
        <View style={{ marginTop: 40 }}>
          {meta.map((m) => (
            <Text key={m.label} style={{ color: "#374151", fontSize: 12 }}>
              {m.label}: {m.value}
            </Text>
          ))}
        </View>
      )}
      {letterhead?.addressText && (
        <Text
          style={{
            color: "#6b7280",
            fontSize: 10,
            position: "absolute",
            bottom: 40,
            textAlign: "center",
          }}
        >
          {letterhead.addressText}
        </Text>
      )}
    </View>
  );
}
