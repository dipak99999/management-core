import * as React from "react";
import { Document, Image, Page, Text, View, StyleSheet } from "@react-pdf/renderer";
import { tf } from "../i18n";

// Data shape kept intentionally loose — callers pass the raw SalesInvoice
// row (with Prisma Decimals coerced to numbers/strings). We format at the
// leaf and don't reach into the DB from this package.

export interface PrintLetterhead {
  logoBase64?: string | null;
  addressText?: string | null;
  footerText?: string | null;
}

export interface PrintFormatOverrides {
  headerText?: string | null;
  footerText?: string | null;
  thankYouNote?: string | null;
  termsText?: string | null;
  showItemDescription?: boolean;
  showTaxBreakdown?: boolean;
  showRemarks?: boolean;
  paperSize?: string;
  orientation?: string;
}

export interface SalesInvoicePrintProps {
  tenantName: string;
  letterhead?: PrintLetterhead | null;
  format?: PrintFormatOverrides | null;
  // BCP-47-ish tag (en, hi, es, de). Unknown → falls back to en. Latin
  // locales (en/es/de) render fine with the default Helvetica font;
  // non-Latin locales (hi) need a Devanagari-capable font registered via
  // Font.register(). See packages/print/src/i18n.ts.
  locale?: string | null;
  invoice: {
    name: string;
    postingDate: string | Date;
    dueDate?: string | Date | null;
    currency: string;
    netTotal: number | string;
    totalTaxes: number | string;
    grandTotal: number | string;
    outstandingAmt: number | string;
    status: string;
    remarks?: string | null;
    customer: {
      customerName: string;
      email?: string | null;
      mobile?: string | null;
      gstin?: string | null;
    };
    items: {
      itemCode?: string;
      itemName?: string;
      description?: string | null;
      qty: number | string;
      rate: number | string;
      amount: number | string;
    }[];
    taxes?: {
      description: string;
      rate: number | string;
      taxAmount: number | string;
    }[];
  };
}

const styles = StyleSheet.create({
  page: {
    padding: 32,
    fontSize: 10,
    fontFamily: "Helvetica",
    color: "#111827",
  },
  headerRow: { flexDirection: "row", justifyContent: "space-between", marginBottom: 16 },
  tenantName: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  docTitle: { fontSize: 20, fontFamily: "Helvetica-Bold", textAlign: "right" },
  docSub: { color: "#6b7280", textAlign: "right" },
  block: { marginBottom: 12 },
  label: { color: "#6b7280", fontSize: 9, marginBottom: 2 },
  strong: { fontFamily: "Helvetica-Bold" },
  hr: { borderBottomWidth: 1, borderBottomColor: "#e5e7eb", marginVertical: 8 },
  th: {
    backgroundColor: "#f3f4f6",
    padding: 6,
    fontFamily: "Helvetica-Bold",
    fontSize: 9,
    color: "#374151",
  },
  td: { padding: 6, borderBottomWidth: 0.5, borderBottomColor: "#e5e7eb" },
  row: { flexDirection: "row" },
  colItem: { flex: 4 },
  colQty: { flex: 1, textAlign: "right" },
  colRate: { flex: 1, textAlign: "right" },
  colAmount: { flex: 1.4, textAlign: "right" },
  totalsBox: { alignSelf: "flex-end", width: 220, marginTop: 12 },
  totalRow: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 3 },
  grandTotalRow: {
    flexDirection: "row",
    justifyContent: "space-between",
    borderTopWidth: 1,
    borderTopColor: "#111827",
    paddingTop: 6,
    marginTop: 4,
  },
  footer: {
    position: "absolute",
    bottom: 24,
    left: 32,
    right: 32,
    fontSize: 8,
    color: "#9ca3af",
    textAlign: "center",
  },
});

function fmt(n: number | string): string {
  return Number(n).toFixed(2);
}

function fmtDate(d: string | Date): string {
  const date = typeof d === "string" ? new Date(d) : d;
  return date.toISOString().slice(0, 10);
}

export function SalesInvoiceDocument({
  tenantName,
  letterhead,
  format,
  invoice,
  locale,
}: SalesInvoicePrintProps) {
  const showDesc = format?.showItemDescription ?? true;
  const showTaxes = format?.showTaxBreakdown ?? true;
  const showRemarks = format?.showRemarks ?? true;
  const size = (format?.paperSize as "A4" | "LETTER" | "LEGAL") ?? "A4";
  const orientation = (format?.orientation as "portrait" | "landscape") ?? "portrait";
  const footerLine =
    format?.footerText ?? letterhead?.footerText ?? "Generated by lumaara";
  const t = tf(locale);
  return (
    <Document title={invoice.name}>
      <Page size={size} orientation={orientation} style={styles.page}>
        <View style={styles.headerRow}>
          <View style={{ flexDirection: "row", alignItems: "flex-start", gap: 12 }}>
            {letterhead?.logoBase64 && (
              <Image
                src={letterhead.logoBase64}
                style={{ width: 64, height: 64, marginRight: 8 }}
              />
            )}
            <View>
              <Text style={styles.tenantName}>{tenantName}</Text>
              <Text style={{ color: "#6b7280" }}>{t("Sales Invoice")}</Text>
              {letterhead?.addressText && (
                <Text style={{ color: "#6b7280", fontSize: 9, marginTop: 2 }}>
                  {letterhead.addressText}
                </Text>
              )}
            </View>
          </View>
          <View>
            <Text style={styles.docTitle}>{invoice.name}</Text>
            <Text style={styles.docSub}>
              {fmtDate(invoice.postingDate)}
              {invoice.dueDate ? `  ·  ${t("due")} ${fmtDate(invoice.dueDate)}` : ""}
            </Text>
            <Text style={styles.docSub}>
              {t("Status")}: {invoice.status}
            </Text>
          </View>
        </View>

        {format?.headerText && (
          <View style={{ marginBottom: 12 }}>
            <Text style={{ color: "#374151" }}>{format.headerText}</Text>
          </View>
        )}

        <View style={styles.block}>
          <Text style={styles.label}>{t("Bill to")}</Text>
          <Text style={styles.strong}>{invoice.customer.customerName}</Text>
          {invoice.customer.email && <Text>{invoice.customer.email}</Text>}
          {invoice.customer.mobile && <Text>{invoice.customer.mobile}</Text>}
          {invoice.customer.gstin && (
            <Text style={{ color: "#6b7280" }}>GSTIN: {invoice.customer.gstin}</Text>
          )}
        </View>

        <View style={styles.hr} />

        <View>
          <View style={[styles.row, styles.th]}>
            <Text style={styles.colItem}>{t("Item")}</Text>
            <Text style={styles.colQty}>{t("Qty")}</Text>
            <Text style={styles.colRate}>{t("Rate")}</Text>
            <Text style={styles.colAmount}>{t("Amount")}</Text>
          </View>
          {invoice.items.map((it, i) => (
            <View key={i} style={[styles.row, styles.td]}>
              <View style={styles.colItem}>
                <Text style={styles.strong}>
                  {it.itemCode ? `${it.itemCode} — ` : ""}
                  {it.itemName ?? ""}
                </Text>
                {showDesc && it.description && (
                  <Text style={{ color: "#6b7280", fontSize: 9 }}>{it.description}</Text>
                )}
              </View>
              <Text style={styles.colQty}>{Number(it.qty)}</Text>
              <Text style={styles.colRate}>{fmt(it.rate)}</Text>
              <Text style={styles.colAmount}>{fmt(it.amount)}</Text>
            </View>
          ))}
        </View>

        <View style={styles.totalsBox}>
          <View style={styles.totalRow}>
            <Text>{t("Subtotal")}</Text>
            <Text>
              {fmt(invoice.netTotal)} {invoice.currency}
            </Text>
          </View>
          {showTaxes &&
            invoice.taxes?.map((tx, i) => (
              <View key={i} style={styles.totalRow}>
                <Text style={{ color: "#6b7280" }}>
                  {tx.description} ({Number(tx.rate)}%)
                </Text>
                <Text>{fmt(tx.taxAmount)}</Text>
              </View>
            ))}
          <View style={styles.grandTotalRow}>
            <Text style={styles.strong}>{t("Grand Total")}</Text>
            <Text style={styles.strong}>
              {fmt(invoice.grandTotal)} {invoice.currency}
            </Text>
          </View>
          <View style={styles.totalRow}>
            <Text style={{ color: "#6b7280" }}>{t("Outstanding")}</Text>
            <Text style={{ color: "#6b7280" }}>
              {fmt(invoice.outstandingAmt)} {invoice.currency}
            </Text>
          </View>
        </View>

        {showRemarks && invoice.remarks && (
          <View style={{ marginTop: 24 }}>
            <Text style={styles.label}>{t("Remarks")}</Text>
            <Text>{invoice.remarks}</Text>
          </View>
        )}

        {format?.thankYouNote && (
          <View style={{ marginTop: 16 }}>
            <Text style={{ color: "#374151" }}>{format.thankYouNote}</Text>
          </View>
        )}

        {format?.termsText && (
          <View style={{ marginTop: 12 }}>
            <Text style={styles.label}>{t("Terms & Conditions")}</Text>
            <Text style={{ color: "#6b7280", fontSize: 9 }}>{format.termsText}</Text>
          </View>
        )}

        <Text style={styles.footer}>
          {footerLine} · {new Date().toISOString().slice(0, 10)}
        </Text>
      </Page>
    </Document>
  );
}
